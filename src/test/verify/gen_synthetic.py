"""產生確定性合成測試載體（Q4-7）：純 NumPy 公式，不依賴任何編碼器或字型，同一參數必得位元級相同的 y4m。

圖樣：
  flat128    全畫面 Y=128（預測誤差全為 0，容量上限）
  hgrad      水平線性漸層 16→235
  dgrad      對角線性漸層 0→255
  shapes     對角漸層背景 + 隨幀移動的矩形與圓（邊緣產生大預測誤差）
  noise      均勻隨機 Y（seed 固定，高紋理、容量下限）
  black      全 0（全部落在 process band [2,253] 外，容量 0；RSK-01）
  white      全 255（同上）
色度一律 128。輸出 YUV4MPEG2（C420jpeg），並寫出 SOURCES.txt（含生成指令與每檔 SHA-256）。

用法：python src/test/verify/gen_synthetic.py <out_dir> [--frames 24] [--width 1920] [--height 1080]
"""
import os
import sys
import argparse

import numpy as np

from _common import sha256, print_header

PATTERNS = ["flat128", "hgrad", "dgrad", "shapes", "noise", "black", "white"]
NOISE_SEED = 20261027


def frame_y(name, i, w, h, rng):
    if name == "flat128":
        return np.full((h, w), 128, np.uint8)
    if name == "black":
        return np.zeros((h, w), np.uint8)
    if name == "white":
        return np.full((h, w), 255, np.uint8)
    x = np.arange(w, dtype=np.int64)[None, :]
    y = np.arange(h, dtype=np.int64)[:, None]
    if name == "hgrad":
        return np.broadcast_to((16 + (219 * x + (w - 1) // 2) // (w - 1)).astype(np.uint8), (h, w)).copy()
    dg = ((x + y) * 255 // (w + h - 2)).astype(np.uint8)
    if name == "dgrad":
        return dg
    if name == "shapes":
        img = dg.copy()
        rx = (i * 37) % (w - w // 4)
        img[h // 4:h // 2, rx:rx + w // 4] = 200
        cx, cy, r = (w // 2 + i * 23) % w, (3 * h) // 4, h // 8
        img[(x - cx) ** 2 + (y - cy) ** 2 <= r * r] = 60
        return img
    if name == "noise":
        return rng.integers(0, 256, (h, w), dtype=np.uint8)
    raise ValueError(name)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out_dir")
    ap.add_argument("--frames", type=int, default=24)
    ap.add_argument("--width", type=int, default=1920)
    ap.add_argument("--height", type=int, default=1080)
    a = ap.parse_args()
    print_header(__file__, sys.argv)
    os.makedirs(a.out_dir, exist_ok=True)
    w, h = a.width, a.height
    chroma = np.full(((h + 1) // 2) * ((w + 1) // 2) * 2, 128, np.uint8).tobytes()
    rows = []
    for name in PATTERNS:
        rng = np.random.default_rng(NOISE_SEED)
        path = os.path.join(a.out_dir, f"synthetic_{name}_{w}x{h}_{a.frames}f.y4m")
        with open(path, "wb") as f:
            f.write(f"YUV4MPEG2 W{w} H{h} F24:1 Ip A1:1 C420jpeg\n".encode("ascii"))
            for i in range(a.frames):
                f.write(b"FRAME\n")
                f.write(frame_y(name, i, w, h, rng).tobytes())
                f.write(chroma)
        digest = sha256(path)
        rows.append((os.path.basename(path), os.path.getsize(path), digest))
        print(f"{os.path.basename(path)}  size={os.path.getsize(path)}  sha256={digest}")

    with open(os.path.join(a.out_dir, "SOURCES.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write("Deterministic synthetic carriers (SYSTEM_TEST_PLAN Q4-7). Media files are gitignored; regenerate with:\n")
        f.write(f"  python src/test/verify/gen_synthetic.py {a.out_dir.replace(os.sep, '/')} "
                f"--frames {a.frames} --width {w} --height {h}\n")
        f.write(f"Pure NumPy formulas, noise seed {NOISE_SEED}; chroma fixed at 128; YUV4MPEG2 C420jpeg, 24 fps.\n")
        f.write("License: generated by this project; no third-party content.\n\n")
        f.write("file  size_bytes  sha256\n")
        for r in rows:
            f.write(f"{r[0]}  {r[1]}  {r[2]}\n")


if __name__ == "__main__":
    main()
